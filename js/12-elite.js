    function _projectLogits(x) {
        const logits = [0, 0, 0];
        for (let c = 0; c < 3; c++) {
            const w = TUNED_W[c];
            let acc = TUNED_B[c];
            for (let i = 0; i < FEATURE_DIM; i++) acc += w[i] * x[i];
            logits[c] = acc;
        }
        return logits;
    }

    // Numerically stable logistic.  Called only on the opt-in calibrated
    // path — the default argmax path never touches Math.exp.
    function _sigmoid(x) {
        if (x >= 0) {
            const z = Math.exp(-x);
            return 1.0 / (1.0 + z);
        }
        const z = Math.exp(x);
        return z / (1.0 + z);
    }
    function _calibrate(margin) {
        return _sigmoid(CALIB_A * margin + CALIB_B);
    }

    function _fuse(x, signals, methods, extD, extG) {
        const logits = _projectLogits(x);
        const scores = { core: logits[0], data: logits[1], design: logits[2] };

        if (!methods.length) {
            return { workspace:"core", confidence:0, method:"fallback",
                     signals: signals.slice(0, 20), scores };
        }

        const ranked = [
            { ws: "core",   v: logits[0] },
            { ws: "data",   v: logits[1] },
            { ws: "design", v: logits[2] },
        ].sort((a, b) =>
            (b.v - a.v) ||
            (a.ws === "design" ? -1 : b.ws === "design" ? 1 : 0)
        );
        let topWs    = ranked[0].ws;
        const topV   = ranked[0].v;
        const second = ranked[1].v;
        const margin = topV - second;

        const scale = Math.max(Math.abs(topV), Math.abs(second), 1e-9);
        const guardFired = (margin / scale) < ENTROPY_MARGIN;
        if (guardFired) {
            if      (extD > extG && extD > 0) topWs = "data";
            else if (extG > extD && extG > 0) topWs = "design";
            else                              topWs = "core";
        }

        if (topWs === "core") {
            return { workspace:"core", confidence:0, method:"fallback",
                     signals: signals.slice(0, 20), scores };
        }

        let conf;
        if (CALIBRATED_CONFIDENCE) {
            conf = _calibrate(margin);
            if (guardFired) conf = Math.min(conf, 0.5);
        } else {
            conf = 0.15 + 0.05 * Math.max(topV, 0) + 0.30 * margin;
            if (methods.length >= 2) conf += 0.15;
            if (topV < 2)            conf = Math.min(conf, 0.55);
            if (guardFired)          conf = Math.min(conf, 0.50);
            conf = Math.max(0, Math.min(1, conf));
        }

        return {
            workspace: topWs,
            confidence: Math.round(conf * 1000) / 1000,
            method: methods.length > 1 ? "fused" : methods[0],
            signals: signals.slice(0, 20),
            scores,
        };
    }

    async function detectWorkspaceFull(prompt, files, sniffContents) {
        const signals = [];
        const methods = [];

        const [dExt, gExt] = _scoreExtensions(files);
        if (dExt || gExt) {
            methods.push("extension");
            signals.push("ext:data"   + (dExt >= 0 ? "+" : "") + dExt.toFixed(1));
            signals.push("ext:design" + (gExt >= 0 ? "+" : "") + gExt.toFixed(1));
        }

        let dCont = 0, gCont = 0;
        if (sniffContents && files && files.length) {
            for (const f of files.slice(0, 3)) {
                if (typeof f.slice !== "function") continue;
                const hits = await _sniffContent(f);
                for (const h of hits) {
                    signals.push("content:" + h.ws + ":" + h.reason);
                    if (h.ws === "data")   dCont += CONTENT_PER_HIT;
                    if (h.ws === "design") gCont += CONTENT_PER_HIT;
                }
            }
            dCont = _clampContent(dCont);
            gCont = _clampContent(gCont);
            if (dCont || gCont) methods.push("content");
        }

        const [dP, gP, pMatches] = _scorePrompt(prompt);
        if (dP || gP) { methods.push("prompt"); signals.push(...pMatches); }

        const x = _buildFeatures(dExt, gExt, dCont, gCont, dP, gP);
        return _fuse(x, signals, methods, dExt, gExt);
    }

    const _CACHE = new Map();
    function _cacheKey(prompt, files) {
        if (!files || !files.length) return prompt + "||";
        const parts = [];
        for (const f of files) {
            if (!f) { parts.push(""); continue; }
            parts.push((f.filename || f.name || "") + "\u0001");
        }
        return prompt + "||" + parts.join("\u0002");
    }
    function _cacheGet(key) {
        if (!_CACHE.has(key)) return undefined;
        const v = _CACHE.get(key);
        _CACHE.delete(key);
        _CACHE.set(key, v);
        return v;
    }
    function _cacheSet(key, value) {
        if (_CACHE.has(key)) _CACHE.delete(key);
        _CACHE.set(key, value);
        if (_CACHE.size > CACHE_MAXSIZE) {
            _CACHE.delete(_CACHE.keys().next().value);
        }
    }

    function detectWorkspace(prompt, files) {
        const key = _cacheKey(prompt || "", files);
        const hit = _cacheGet(key);
        if (hit !== undefined) return hit;

        const [dExt, gExt] = _scoreExtensions(files);
        const [dP, gP]     = _scorePrompt(prompt);

        if (!dExt && !gExt && !dP && !gP) {
            _cacheSet(key, "core");
            return "core";
        }
        const x = _buildFeatures(dExt, gExt, 0, 0, dP, gP);
        const methods = [];
        if (dExt || gExt) methods.push("extension");
        if (dP || gP)     methods.push("prompt");

        const r = _fuse(x, [], methods, dExt, gExt);
        _cacheSet(key, r.workspace);
        return r.workspace;
    }

    function routeWorkspace(currentWorkspace, result, threshold) {
        const t = (threshold === undefined) ? SWITCH_THRESHOLD : threshold;
        if (result.confidence >= t && result.workspace !== currentWorkspace) {
            return result.workspace;
        }
        return currentWorkspace;
    }
const STICKY_THRESHOLD = 0.45;
function routeEx(current, result, previous, threshold, sticky) {
    const t = threshold === undefined ? SWITCH_THRESHOLD : threshold;
    const s = sticky   === undefined ? STICKY_THRESHOLD : sticky;
    if (result.workspace === current) return [current, "no_change"];
    if (result.confidence >= t)       return [result.workspace, "switch"];
    if (previous && result.workspace === previous && result.confidence >= s)
        return [result.workspace, "revert"];
    return [current, "below_threshold"];
}
